/**
 * @brief 串口发送指定长度的数据（HAL库版本）
 * @param huart 串口句柄，例如 &huart1
 * @param str   要发送的数据缓冲区（无符号字符数组）
 * @param len   数据长度（字节数）
 * @note  阻塞方式发送，发送完成超时时间为 0xFFFF（可根据实际需求调整）
 */
void Usart_SendString(UART_HandleTypeDef *huart, unsigned char *str, unsigned short len)
{
    if (len > 0)
    {
        HAL_UART_Transmit(huart, (uint8_t*)str, (uint16_t)len, 0xFFFF);
    }
}
/**
 * @brief 格式化输出字符串到指定串口（HAL库版本）
 * @param huart 串口句柄，如 &huart1
 * @param fmt   格式化字符串，与 printf 用法相同
 * @param ...   可变参数
 * @note  使用 HAL_UART_Transmit 一次性发送整个字符串，阻塞方式
 */
void UsartPrintf(UART_HandleTypeDef *huart, char *fmt,...)
{
    unsigned char UsartPrintfBuf[296];  // 缓冲区大小可根据需要调整
    va_list ap;
    int len;

    va_start(ap, fmt);
    len = vsnprintf((char *)UsartPrintfBuf, sizeof(UsartPrintfBuf), fmt, ap);
    va_end(ap);

    // 仅当格式化成功且未超出缓冲区时才发送
    if (len > 0 && len < (int)sizeof(UsartPrintfBuf))
    {
        HAL_UART_Transmit(huart, UsartPrintfBuf, (uint16_t)len, 0xFFFF);
    }
}
